#!/usr/bin/env node
/**
 * Keeps the stories in step with the Astryx manifest (packages/astryx-astro/meta/astryx-docs.json).
 *
 *   node scripts/stories.mjs              regenerate stories/_lib/catalog.generated.ts and
 *                                         scaffold stories/<Name>/<Name>.stories.ts (Overview
 *                                         story only) for every component that has none
 *   node scripts/stories.mjs --check      fail (exit 1) when the catalog is stale, a manifest
 *                                         component has no story file, or a story file breaks
 *                                         the conventions in STORIES.md that can be checked
 *                                         statically
 *
 * Package scripts: `pnpm -F storybook stories` and `pnpm -F storybook check`.
 */
import {existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const app = dirname(dirname(fileURLToPath(import.meta.url)));
const pkg = join(app, '../../packages/astryx-astro');
const componentsDir = join(pkg, 'src/components');
const storiesDir = join(app, 'stories');
const catalogFile = join(storiesDir, '_lib/catalog.generated.ts');
const registryFile = join(app, '.storybook/script-registry/ScriptRegistry.generated.astro');
const previewFile = join(app, '.storybook/preview.ts');
const check = process.argv.includes('--check');

/** Sidebar order: the docs site's (apps/docs/src/lib/catalog.ts categoryOrder). */
export const categoryOrder = [
  'Layout', 'Content', 'Action', 'Form Controls', 'Container', 'Feedback & Status',
  'Navigation', 'Overlay', 'Table & List', 'Chat', 'Utility',
];

/**
 * Manifest entries with no `<Name>.astro`: the component a story file documents and
 * pre-renders instead (`meta.component` must be an .astro file for the static build).
 */
const primaryComponent = {Chat: 'ChatLayout', Resizable: 'ResizeHandle'};

const manifest = JSON.parse(readFileSync(join(pkg, 'meta/astryx-docs.json'), 'utf8'));
const dirs = readdirSync(componentsDir, {withFileTypes: true}).filter((d) => d.isDirectory()).map((d) => d.name);
const locate = (file) => {
  const hits = dirs.filter((d) => existsSync(join(componentsDir, d, file)));
  return hits.length === 1 ? `${hits[0]}/${file}` : null;
};

const problems = [];
const entries = manifest.components
  .filter((c) => !c.subComponentOf)
  .map((c) => {
    const main = primaryComponent[c.name] ?? c.name;
    const component = locate(`${main}.astro`);
    const demo = locate(`${c.name}.demo.astro`);
    if (!component) problems.push(`${c.name}: no single ${main}.astro under src/components (add it to primaryComponent)`);
    if (!demo) problems.push(`${c.name}: no single ${c.name}.demo.astro under src/components`);
    if (!categoryOrder.includes(c.category ?? 'Utility')) problems.push(`${c.name}: category "${c.category}" is not in categoryOrder`);
    const subComponents = manifest.components
      .filter((s) => s.subComponentOf === c.name)
      .map((s) => ({name: s.name, path: locate(`${s.name}.astro`)}))
      .filter((s) => s.path && s.name !== main);
    return {
      name: c.name,
      displayName: c.displayName,
      category: c.category ?? 'Utility',
      title: `${c.category ?? 'Utility'}/${c.displayName}`,
      description: c.description,
      hidden: c.hidden,
      component: component && {name: main, path: component},
      demo,
      subComponents,
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

// ---------------------------------------------------------------------------------------------
// catalog.generated.ts
// ---------------------------------------------------------------------------------------------

const catalogSource = `// @generated by apps/storybook/scripts/stories.mjs from packages/astryx-astro/meta/astryx-docs.json.
// Do not edit: run \`pnpm -F storybook stories\`.

/** Sidebar category order (the docs site's). */
export const categoryOrder = ${JSON.stringify(categoryOrder)} as const;

export interface CatalogEntry {
  /** Storybook title: \`<category>/<displayName>\`. */
  readonly title: string;
  readonly category: (typeof categoryOrder)[number];
  readonly displayName: string;
  /** The manifest description: the docs page lede and the autodocs description. */
  readonly description: string;
  /** Astryx hides it from its own docs index (still ported and documented here). */
  readonly hidden: boolean;
  /** The .astro file the story file documents, relative to astryx-astro/components. */
  readonly component: string;
  /** The docs demo the Overview story renders, relative to astryx-astro/components. */
  readonly demo: string;
  /** Sub-components (manifest \`subComponentOf\`), name → path relative to astryx-astro/components. */
  readonly subComponents: Readonly<Record<string, string>>;
}

export const catalog = {
${entries
  .map((e) => `  ${e.name}: ${JSON.stringify({
    title: e.title,
    category: e.category,
    displayName: e.displayName,
    description: e.description,
    hidden: e.hidden,
    component: e.component?.path ?? null,
    demo: e.demo,
    subComponents: Object.fromEntries(e.subComponents.map((s) => [s.name, s.path])),
  })},`)
  .join('\n')}
} as const satisfies Record<string, CatalogEntry>;

export type ComponentName = keyof typeof catalog;
`;

// ---------------------------------------------------------------------------------------------
// ScriptRegistry.generated.astro
// ---------------------------------------------------------------------------------------------

/** Every .astro file under `dir`, recursively, sorted. */
function astroFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, {withFileTypes: true, recursive: true})
    .filter((d) => d.isFile() && d.name.endsWith('.astro'))
    .map((d) => join(d.parentPath ?? d.path, d.name))
    .sort();
}

const registered = [
  ...astroFiles(componentsDir),
  ...astroFiles(storiesDir).filter((f) => f !== registryFile),
];
const registrySource = `---
// @generated by apps/storybook/scripts/stories.mjs. Do not edit: run \`pnpm -F storybook stories\`.
//
// Not rendered (its story is hidden). It exists so \`storybook build\` bundles the <script> of
// every component: @storybook-astro/framework collects component scripts by following relative
// .astro imports from each story file's meta.component, which never reaches the components a
// docs demo or a story wrapper renders. This file is the meta.component of
// ScriptRegistry.stories.ts (added to \`storybook build\` only, see main.ts) and imports every
// .astro file in astryx-astro and in stories/.
// The imports are unused, so the compiled module never loads them: the framework reads them
// from this file's source.
${registered.map((f, i) => `import C${i} from '${relative(dirname(registryFile), f).split('\\').join('/')}';`).join('\n')}
---
`;

// ---------------------------------------------------------------------------------------------
// Scaffold: stories/<Name>/<Name>.stories.ts with the Overview story
// ---------------------------------------------------------------------------------------------

const storyFile = (name) => join(storiesDir, name, `${name}.stories.ts`);

function scaffold(e) {
  const C = e.component.name;
  return `import ${C} from 'astryx-astro/components/${e.component.path}';
import Demo from 'astryx-astro/components/${e.demo}';
import demoSource from 'astryx-astro/components/${e.demo}?raw';
import {astryx, overview, type Meta} from '../_lib/story';

const meta = {
  title: '${e.title}',
  component: ${C},
  ...astryx('${e.name}'),
} satisfies Meta;
export default meta;

/** Every example from the docs page (${e.demo.split('/').pop()}), pre-rendered as one story. */
export const Overview = overview(Demo, demoSource);
`;
}

// ---------------------------------------------------------------------------------------------
// Checks on story files (what STORIES.md requires and a regex can see)
// ---------------------------------------------------------------------------------------------

function checkStoryFile(e) {
  const file = storyFile(e.name);
  const rel = relative(app, file);
  if (!existsSync(file)) return [`${e.name}: missing ${rel} (run \`pnpm -F storybook stories\` to scaffold it)`];
  const src = readFileSync(file, 'utf8');
  const out = [];
  const title = src.match(/^\s*title:\s*(['"])(.*?)\1/m)?.[2];
  if (title !== e.title) out.push(`${rel}: title must be '${e.title}' (found ${title ? `'${title}'` : 'none'})`);
  const componentId = src.match(/^\s*component:\s*([A-Za-z_$][\w$]*)\s*,/m)?.[1];
  const importRe = new RegExp(`^import\\s+${componentId ?? '\\0'}\\s+from\\s+'astryx-astro/components/([^']+)';`, 'm');
  const imported = componentId && src.match(importRe)?.[1];
  if (imported !== e.component?.path) out.push(`${rel}: meta.component must be imported from 'astryx-astro/components/${e.component?.path}'`);
  if (!new RegExp(`\\.\\.\\.astryx\\('${e.name}'[),]`).test(src)) out.push(`${rel}: meta must spread astryx('${e.name}')`);
  if (!/^export const Overview = overview\(/m.test(src)) out.push(`${rel}: needs \`export const Overview = overview(Demo, demoSource)\``);
  const firstStory = src.match(/^export const (\w+)/m)?.[1];
  if (firstStory && firstStory !== 'Overview') out.push(`${rel}: Overview must be the first story (found ${firstStory})`);
  // Story components other than meta.component are dropped from the static build.
  if (/^\s{2,}component:\s/m.test(src.replace(/^const meta = \{[\s\S]*?^\} satisfies Meta;/m, ''))) {
    out.push(`${rel}: a story must not override \`component\` (use a story wrapper with composed())`);
  }
  if (/\bTemporal\.\w+\.from\(|\bnew Date\(/.test(src)) {
    out.push(`${rel}: Temporal/Date values go in a story wrapper's frontmatter, not in args (args cross JSON in dev)`);
  }
  return out;
}

function checkPreviewOrder() {
  const src = readFileSync(previewFile, 'utf8');
  const order = src.match(/order:\s*\[([^\]]*)\]/)?.[1];
  const listed = order ? [...order.matchAll(/'([^']+)'/g)].map((m) => m[1]).filter((c) => c !== 'Introduction') : [];
  return JSON.stringify(listed) === JSON.stringify(categoryOrder)
    ? []
    : [`.storybook/preview.ts: options.storySort.order must be ['Introduction', ...${JSON.stringify(categoryOrder)}]`];
}

// ---------------------------------------------------------------------------------------------

const stale = !existsSync(catalogFile) || readFileSync(catalogFile, 'utf8') !== catalogSource;
const registryStale = !existsSync(registryFile) || readFileSync(registryFile, 'utf8') !== registrySource;
const known = new Set(entries.map((e) => e.name));
const extra = existsSync(storiesDir)
  ? readdirSync(storiesDir, {withFileTypes: true})
      .filter((d) => d.isDirectory() && !d.name.startsWith('_') && !known.has(d.name))
      .map((d) => `stories/${d.name}: not a manifest component (story folders are named after manifest entries)`)
  : [];

if (check) {
  const failures = [
    ...problems,
    ...(stale ? ['stories/_lib/catalog.generated.ts is stale (run `pnpm -F storybook stories`)'] : []),
    ...(registryStale ? ['.storybook/script-registry/ScriptRegistry.generated.astro is stale (run `pnpm -F storybook stories`)'] : []),
    ...entries.flatMap(checkStoryFile),
    ...checkPreviewOrder(),
    ...extra,
  ];
  if (failures.length) {
    console.error(`✗ ${failures.length} problem(s):\n${failures.map((f) => `  - ${f}`).join('\n')}`);
    process.exit(1);
  }
  console.log(`✓ ${entries.length} components: catalog and script registry current, every component has a conforming story file`);
} else {
  if (problems.length) {
    console.error(problems.join('\n'));
    process.exit(1);
  }
  mkdirSync(dirname(catalogFile), {recursive: true});
  if (stale) writeFileSync(catalogFile, catalogSource);
  let created = 0;
  for (const e of entries) {
    const file = storyFile(e.name);
    if (existsSync(file)) continue;
    mkdirSync(dirname(file), {recursive: true});
    writeFileSync(file, scaffold(e));
    created++;
  }
  // After scaffolding: the registry lists story wrappers too.
  const registryNow = registrySource;
  if (registryStale) writeFileSync(registryFile, registryNow);
  console.log(`catalog ${stale ? 'updated' : 'current'}, script registry ${registryStale ? 'updated' : 'current'} (${registered.length} .astro files); scaffolded ${created} story file(s); ${entries.length} components`);
}
