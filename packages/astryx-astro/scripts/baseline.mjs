#!/usr/bin/env node
/**
 * Platform policy check (docs/platform.md). Reads scripts/platform-features.json and the
 * pinned web-features data (an exact devDependency) and:
 *   - fails when a `required` feature is not Baseline (web-features status "low" or "high");
 *     with `keys`, each listed compat key must be Baseline too, and with `partial: true` only
 *     the keys count (the feature as a whole is not Baseline);
 *   - reports `enhancement` features that have become Baseline (promote them: drop their
 *     detection / fallback and mark them required);
 *   - fails when the installed web-features is not the pinned version, an id or key is
 *     unknown, an enhancement says nothing about how it degrades, or the generated tables in
 *     docs/platform.md are out of date.
 *   node scripts/baseline.mjs [--write]   (--write regenerates the tables in docs/platform.md)
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(join(pkgRoot, 'package.json'));
const docPath = join(pkgRoot, 'docs/platform.md');
const BEGIN = '<!-- baseline:begin — generated by scripts/baseline.mjs --write from scripts/platform-features.json; do not edit -->';
const END = '<!-- baseline:end -->';

const pinned = JSON.parse(readFileSync(join(pkgRoot, 'package.json'), 'utf8')).devDependencies?.['web-features'];
// The package exports no ./package.json: read it beside its entry point.
const installed = JSON.parse(readFileSync(join(dirname(require.resolve('web-features')), 'package.json'), 'utf8')).version;
const {features} = await import('web-features');
const {features: entries} = JSON.parse(readFileSync(join(pkgRoot, 'scripts/platform-features.json'), 'utf8'));

const errors = [];
const promotable = [];
if (pinned !== installed) errors.push(`web-features ${installed} is installed but package.json pins ${pinned ?? '(nothing)'}; run pnpm install`);
if (!/^\d+\.\d+\.\d+$/.test(pinned ?? '')) errors.push(`web-features must be pinned to an exact release, not ${JSON.stringify(pinned)}`);

const RANK = {false: 0, low: 1, high: 2};
const isBaseline = (s) => s.baseline === 'low' || s.baseline === 'high';
/** The weakest of several statuses; its date is the latest low date among them. */
function weakest(list) {
  let baseline = 'high';
  let date = '';
  for (const s of list) {
    if (RANK[String(s.baseline)] < RANK[baseline]) baseline = String(s.baseline);
    if ((s.baseline_low_date ?? '') > date) date = s.baseline_low_date;
  }
  return {baseline: baseline === 'false' ? false : baseline, baseline_low_date: baseline === 'false' ? undefined : date || undefined};
}
const label = (s) => (isBaseline(s) ? `${s.baseline} · ${s.baseline_low_date}` : 'no');
const cell = (text) => String(text).replaceAll('|', '\\|').replaceAll('\n', ' ');
/** A web-features name as table text (some are tags, such as `<dialog>`). */
const nameCell = (text) => cell(text).replaceAll('<', '&lt;').replaceAll('>', '&gt;');

const rows = [];
const seen = new Set();
for (const entry of entries) {
  const {id, use} = entry;
  if (seen.has(id)) errors.push(`${id}: listed twice`);
  seen.add(id);
  if (use !== 'required' && use !== 'enhancement') { errors.push(`${id}: use must be "required" or "enhancement"`); continue; }
  if (!entry.where) errors.push(`${id}: missing "where"`);
  if (use === 'enhancement' && !entry.degrades) errors.push(`${id}: an enhancement needs "degrades"`);
  if (entry.partial && !entry.keys?.length) errors.push(`${id}: partial needs keys`);
  const feature = features[id];
  if (!feature) { errors.push(`${id}: not a web-features id`); continue; }
  if (feature.kind !== 'feature') {
    errors.push(`${id}: web-features lists it as ${feature.kind}${feature.redirect_target ? ` → ${feature.redirect_target}` : ''}${feature.redirect_targets ? ` → ${feature.redirect_targets.join(', ')}` : ''}`);
    continue;
  }
  const keyStatuses = [];
  for (const key of entry.keys ?? []) {
    const status = feature.status.by_compat_key?.[key];
    if (!status) { errors.push(`${id}: ${key} is not one of its compat keys`); continue; }
    keyStatuses.push({key, ...status});
  }
  const keys = keyStatuses.length ? weakest(keyStatuses) : null;
  const effective = entry.partial ? keys ?? {baseline: false} : weakest([feature.status, ...(keys ? [keys] : [])]);
  if (use === 'required' && !isBaseline(effective)) {
    const missing = keyStatuses.filter((k) => !isBaseline(k)).map((k) => k.key);
    errors.push(`${id}: required but not Baseline in web-features ${installed}${missing.length ? ` (keys: ${missing.join(', ')})` : ''}`);
  }
  if (use === 'enhancement' && isBaseline(effective)) promotable.push(`${id} (${label(effective)})`);
  const status = entry.partial
    ? `${label(feature.status)}; keys used: ${label(effective)}`
    : keys ? `${label(feature.status)}; keys: ${label(keys)}` : label(feature.status);
  rows.push({entry, name: feature.name, status, keyStatuses});
}

// ── docs/platform.md tables ──────────────────────────────────────────────────
const required = rows.filter((r) => r.entry.use === 'required');
const enhancements = rows.filter((r) => r.entry.use === 'enhancement');
const lines = [
  BEGIN,
  '',
  `Statuses from web-features ${installed}. ${required.length} required, ${enhancements.length} enhancements.`,
  '',
  '### Required (used without a fallback)',
  '',
  '| Feature | web-features id | Baseline | Where |',
  '|---|---|---|---|',
  ...required.map((r) => `| ${nameCell(r.name)} | \`${r.entry.id}\` | ${cell(r.status)} | ${cell(r.entry.where)} |`),
  '',
  '### Enhancements (not Baseline: detected or harmless when missing)',
  '',
  '| Feature | web-features id | Baseline | Where | Without it |',
  '|---|---|---|---|---|',
  ...enhancements.map((r) => `| ${nameCell(r.name)} | \`${r.entry.id}\` | ${cell(r.status)} | ${cell(r.entry.where)} | ${cell(r.entry.degrades)} |`),
  '',
  '### Compat keys checked',
  '',
  'Where an entry lists compat keys, each must be Baseline too (for a partial entry, only they count).',
  '',
  '| Entry | Compat key | Baseline |',
  '|---|---|---|',
  ...rows.flatMap((r) => r.keyStatuses.map((k) => `| \`${r.entry.id}\`${r.entry.partial ? ' (partial)' : ''} | \`${k.key}\` | ${label(k)} |`)),
  '',
  ...(rows.some((r) => r.entry.note) ? ['### Notes', '', ...rows.filter((r) => r.entry.note).map((r) => `- \`${r.entry.id}\`: ${r.entry.note}`), ''] : []),
  END,
];
const generated = lines.join('\n');
const doc = readFileSync(docPath, 'utf8');
const begin = doc.indexOf('<!-- baseline:begin');
const end = doc.indexOf(END);
if (begin === -1 || end === -1 || end < begin) {
  errors.push(`docs/platform.md has no ${BEGIN.slice(0, 22)}… / ${END} markers`);
} else {
  const next = doc.slice(0, begin) + generated + doc.slice(end + END.length);
  if (process.argv.includes('--write')) {
    if (next !== doc) writeFileSync(docPath, next);
    console.log(next === doc ? 'docs/platform.md is up to date' : 'docs/platform.md tables regenerated');
  } else if (next !== doc) {
    errors.push('docs/platform.md tables are out of date: run node scripts/baseline.mjs --write');
  }
}

console.log(`web-features ${installed}: ${required.length} required, ${enhancements.length} enhancements`);
for (const p of promotable) console.log(`  now Baseline, consider promoting: ${p}`);
for (const e of errors) console.error(`  ✗ ${e}`);
if (errors.length) process.exit(1);
console.log(`  ✓ every required feature is Baseline${promotable.length ? '' : '; no enhancement has become Baseline'}`);
