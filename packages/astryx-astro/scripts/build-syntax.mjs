#!/usr/bin/env node
/**
 * Generates src/styles/syntax.css — the syntax-highlighting domain tokens — from Astryx's own
 * source, read as text (nothing from the package is executed):
 *
 *  - `:root` defaults: @astryxdesign/core src/theme/syntax/tokens.ts (`syntaxTokenDefaults`,
 *    the values CodeBlock's highlightStyles.ts injects as its fallback `:root` block). Here
 *    they live in `@layer astryx-base`, so a theme's own `--color-syntax-*` (every shipped
 *    theme sets them, `defineTheme({syntax})`) and SyntaxTheme presets override them.
 *  - one `[data-astryx-syntax-theme="<name>"]` block per preset in src/theme/syntax/presets.ts,
 *    resolved exactly as `defineSyntaxTheme()` does: [light, dark] tuples → light-dark(),
 *    unset diff slots keep their defaults, unset markers follow the theme's punctuation and an
 *    unset diff header is transparent.
 *
 * SyntaxTheme (components/theme/SyntaxTheme.astro) imports the file and writes the attribute.
 *
 * Run: node scripts/build-syntax.mjs           (writes)
 *      node scripts/build-syntax.mjs --check   (exits 1 when the committed output is stale)
 */
import {existsSync, readFileSync, writeFileSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {fileURLToPath} from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const coreDir = join(pkgRoot, 'node_modules/@astryxdesign/core');
if (!existsSync(join(coreDir, 'package.json'))) throw new Error('@astryxdesign/core is not installed — run pnpm install');
const core = JSON.parse(readFileSync(join(coreDir, 'package.json'), 'utf8'));
const syntaxDir = join(coreDir, 'src/theme/syntax');
const out = join(pkgRoot, 'src/styles/syntax.css');

// ---------------------------------------------------------------------------
// Defaults (tokens.ts)
// ---------------------------------------------------------------------------
const tokensSrc = readFileSync(join(syntaxDir, 'tokens.ts'), 'utf8');
const defaultsBody = tokensSrc.match(/export const syntaxTokenDefaults = \{([\s\S]*?)\n\} as const;/)?.[1];
if (!defaultsBody) throw new Error('syntaxTokenDefaults not found in tokens.ts — source shape changed?');
const defaults = new Map();
for (const m of defaultsBody.replace(/\/\/.*$/gm, '').matchAll(/'(--color-syntax-[a-z-]+)':\s*'([^']*)'/g)) defaults.set(m[1], m[2]);
const diffNames = tokensSrc.match(/DIFF_SYNTAX_TOKEN_NAMES = \[([\s\S]*?)\]/)?.[1].match(/--color-syntax-[a-z-]+/g) ?? [];
if (defaults.size < 14 || diffNames.length === 0) throw new Error(`unexpected syntax token defaults (${defaults.size}, ${diffNames.length} diff slots)`);
const keys = [...defaults.keys()].map((name) => name.replace('--color-syntax-', ''));
const diffKeys = new Set(diffNames.map((n) => n.replace('--color-syntax-', '')));
const markerKeys = new Set(['added-marker', 'removed-marker']);

// ---------------------------------------------------------------------------
// Presets (presets.ts)
// ---------------------------------------------------------------------------
const presetsSrc = readFileSync(join(syntaxDir, 'presets.ts'), 'utf8');
const presets = [];
for (const m of presetsSrc.matchAll(/(\/\*\*[^*]*\*\/)?\s*export const (\w+): SyntaxThemeDefinition = defineSyntaxTheme\(\{\s*name: '([^']+)',\s*tokens: \{([\s\S]*?)\},\s*\}\);/g)) {
  const [, comment, exportName, name, body] = m;
  const input = new Map();
  for (const t of body.matchAll(/'?([a-z-]+)'?:\s*(\[[^\]]*\]|'[^']*')/g)) {
    const raw = t[2];
    const value = raw.startsWith('[')
      ? `light-dark(${[...raw.matchAll(/'([^']*)'/g)].map((v) => v[1]).join(', ')})`
      : raw.slice(1, -1);
    input.set(t[1], value);
  }
  const resolved = keys.map((key) => {
    const value = input.has(key)
      ? input.get(key)
      : markerKeys.has(key) ? 'var(--color-syntax-punctuation)'
      : key === 'diff-header' ? 'transparent'
      : defaults.get(`--color-syntax-${key}`);
    return [`--color-syntax-${key}`, value];
  });
  const missing = keys.filter((k) => !diffKeys.has(k) && !input.has(k));
  if (missing.length) throw new Error(`preset ${name} misses ${missing.join(', ')}`);
  presets.push({exportName, name, note: comment?.replace(/^\/\*\*\s*|\s*\*\/$/g, '') ?? '', resolved});
}
if (presets.length < 10) throw new Error(`only ${presets.length} syntax presets parsed — source shape changed?`);

// ---------------------------------------------------------------------------
// Output
// ---------------------------------------------------------------------------
const decls = (entries, indent) => entries.map(([k, v]) => `${indent}${k}: ${v};`).join('\n');
const css =
  `/*\n * @generated by scripts/build-syntax.mjs — do not edit manually.\n` +
  ` * Source: @astryxdesign/core src/theme/syntax/tokens.ts (syntaxTokenDefaults) and src/theme/syntax/presets.ts\n` +
  ` * Astryx: @astryxdesign/core@${core.version} (MIT, Copyright (c) Meta Platforms, Inc. and affiliates.)\n` +
  ` * Preset palettes are color values from MIT-licensed community themes; see\n` +
  ` * @astryxdesign/core src/theme/syntax/THIRD_PARTY_LICENSES.md for attribution.\n */\n\n` +
  `@layer reset, astryx-base, astryx-theme;\n\n@layer astryx-base {\n` +
  `  :root {\n${decls([...defaults], '    ')}\n  }\n` +
  presets.map((p) => `\n  /* ${p.exportName}${p.note ? ` — ${p.note}` : ''} */\n  [data-astryx-syntax-theme="${p.name}"] {\n${decls(p.resolved, '    ')}\n  }\n`).join('') +
  `}\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== css) {
    console.error(`stale: ${relative(pkgRoot, out)}`);
    process.exit(1);
  }
} else writeFileSync(out, css);
console.log(`${defaults.size} syntax tokens, ${presets.length} presets → ${relative(pkgRoot, out)}`);
