#!/usr/bin/env node
/**
 * Generates the design-token and theme stylesheets from Astryx's own source.
 *
 *  - tokens.css   core default tokens, lifted from @astryxdesign/core's compiled
 *                 StyleX output (the `:root, .x…{}` blocks that defineVars emits)
 *  - reset.css    @astryxdesign/core's reset, verbatim
 *  - themes/*.css every published theme rebuilt with `astryx theme build`
 *                 from the theme package's TypeScript source
 *  - themes/*.fonts.css the theme's web-font imports
 *  - tokens.json  token name inventory (used by the docs site)
 *
 * Run: pnpm tokens            (writes)
 *      pnpm tokens --check    (exits 1 when committed output is stale)
 */
import {execFileSync} from 'node:child_process';
import {mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync, existsSync} from 'node:fs';
import {dirname, join, relative} from 'node:path';
import {tmpdir} from 'node:os';
import {fileURLToPath} from 'node:url';

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const stylesDir = join(pkgRoot, 'src/styles');
const themesDir = join(stylesDir, 'themes');
// Theme builds go to a temp folder so `--check` never writes inside the package.
const buildDir = mkdtempSync(join(tmpdir(), 'astryx-tokens-'));
const check = process.argv.includes('--check');

export const THEMES = ['neutral', 'butter', 'chocolate', 'gothic', 'matcha', 'stone', 'y2k'];

// Astryx packages don't export ./package.json, so resolve the install folder directly.
const pkgDir = (name) => {
  const dir = join(pkgRoot, 'node_modules', name);
  if (!existsSync(join(dir, 'package.json'))) throw new Error(`${name} is not installed — run pnpm install`);
  return dir;
};
const corePkg = JSON.parse(readFileSync(join(pkgDir('@astryxdesign/core'), 'package.json'), 'utf8'));
const coreDir = pkgDir('@astryxdesign/core');

const header = (source) =>
  `/*\n * @generated by scripts/build-tokens.mjs — do not edit manually.\n * Source: ${source}\n * Astryx: @astryxdesign/core@${corePkg.version} (MIT, Copyright (c) Meta Platforms, Inc. and affiliates.)\n */\n\n`;

const outputs = new Map();

// ---------------------------------------------------------------------------
// 1. Core default tokens
// ---------------------------------------------------------------------------
const compiled = readFileSync(join(coreDir, 'dist/astryx.css'), 'utf8');
const blocks = [...compiled.matchAll(/:root, \.x[a-z0-9]+\{([^}]*)\}/g)].map((m) => m[1]);
if (blocks.length === 0) throw new Error('No :root token blocks found in astryx.css — StyleX output shape changed?');

const declarations = [];
for (const block of blocks) {
  for (const decl of block.split(/;(?![^(]*\))/)) {
    const d = decl.trim();
    if (d.startsWith('--')) declarations.push(d);
  }
}
const tokenNames = declarations.map((d) => d.slice(0, d.indexOf(':')));
outputs.set(
  join(stylesDir, 'tokens.css'),
  header('@astryxdesign/core dist/astryx.css (stylex.defineVars defaults)') +
    '@layer reset, astryx-base, astryx-theme;\n\n@layer astryx-base {\n  :root {\n' +
    declarations.map((d) => `    ${d};`).join('\n') +
    '\n  }\n}\n',
);

// ---------------------------------------------------------------------------
// 2. Reset
// ---------------------------------------------------------------------------
outputs.set(join(stylesDir, 'reset.css'), header('@astryxdesign/core src/reset.css') + readFileSync(join(coreDir, 'src/reset.css'), 'utf8'));

// ---------------------------------------------------------------------------
// 3. Themes — rebuilt from TypeScript source with the Astryx CLI
// ---------------------------------------------------------------------------
rmSync(buildDir, {recursive: true, force: true});
mkdirSync(buildDir, {recursive: true});
const themeTokens = {};
for (const theme of THEMES) {
  const dir = pkgDir(`@astryxdesign/theme-${theme}`);
  const source = join(dir, `src/${theme}Theme.ts`);
  const out = join(buildDir, `${theme}.css`);
  // The CLI only writes inside its working directory, so run it from the temp folder.
  execFileSync(join(pkgRoot, 'node_modules/.bin/astryx'), ['theme', 'build', source, '--out', `${theme}.css`], {
    cwd: buildDir,
    stdio: ['ignore', 'ignore', 'inherit'],
  });
  const css = readFileSync(out, 'utf8').replace(/^\/\*[\s\S]*?\*\/\s*/, '');
  outputs.set(join(themesDir, `${theme}.css`), header(`@astryxdesign/theme-${theme} src/${theme}Theme.ts via \`astryx theme build\``) + css);
  themeTokens[theme] = [...new Set(css.match(/--[a-z][a-z0-9-]*(?=\s*:)/g) ?? [])];
  const fonts = join(dir, 'fonts.css');
  if (existsSync(fonts)) {
    outputs.set(join(themesDir, `${theme}.fonts.css`), header(`@astryxdesign/theme-${theme} fonts.css`) + readFileSync(fonts, 'utf8').replace(/^\/\*.*?\*\/\s*/, ''));
  }
}
rmSync(buildDir, {recursive: true, force: true});

// ---------------------------------------------------------------------------
// 4. Locales — Astryx's ICU message catalogs, without translator notes
// ---------------------------------------------------------------------------
const localesSrc = join(coreDir, 'locales');
const locales = readdirSync(localesSrc).filter((f) => f.endsWith('.json')).sort();
for (const file of locales) {
  const catalog = JSON.parse(readFileSync(join(localesSrc, file), 'utf8'));
  const messages = Object.fromEntries(
    Object.entries(catalog).map(([key, value]) => [key, typeof value === 'string' ? value : value.defaultMessage]),
  );
  outputs.set(join(pkgRoot, 'src/locales', file), JSON.stringify(messages, null, 1) + '\n');
}

outputs.set(
  join(stylesDir, 'tokens.json'),
  JSON.stringify({astryx: corePkg.version, themes: THEMES, tokens: tokenNames, themeOverrides: themeTokens}, null, 2) + '\n',
);

// ---------------------------------------------------------------------------
// Write or check
// ---------------------------------------------------------------------------
let stale = 0;
for (const [file, content] of outputs) {
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== content) {
      console.error(`stale: ${relative(pkgRoot, file)}`);
      stale++;
    }
  } else {
    mkdirSync(dirname(file), {recursive: true});
    writeFileSync(file, content);
  }
}
if (check && stale) process.exit(1);
console.log(`${check ? 'checked' : 'wrote'} ${outputs.size} files — ${tokenNames.length} core tokens, ${THEMES.length} themes (Astryx ${corePkg.version})`);
